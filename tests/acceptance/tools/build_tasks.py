KEY_RX = re.compile(r"(?:^|[\s(!\-])(" + "|".join(sorted(map(re.escape, KEY_CANON), key=len, reverse=True)) + r")\s*[:=]")


def dsl_keys(queries: list[dict]) -> list[str]:
    keys: list[str] = []
    for q in queries:
        text = q["q"]
        found = [KEY_CANON[m.group(1).lower()] for m in KEY_RX.finditer(text)]
        stripped = re.sub(r"\S+\s*[:=]\s*(\([^)]*\)(~\S+)?|\"[^\"]*\"|/[^/]*/|\S+)", " ", text)
        if re.search(r"/[^/]+/", text):
            found.append("регэксп")
        if re.search(r"[^\s\-()|]", stripped):
            found.append("текст")
        for k in found:
            if k not in keys:
                keys.append(k)
    return keys


def words(s: str) -> list[str]:
    return re.findall(r"[0-9a-zа-яёა-ჰ]+", s.lower())


def shingles(ws: list[str], n: int) -> set[tuple[str, ...]]:
    return {tuple(ws[i:i + n]) for i in range(len(ws) - n + 1)}


def category_of(raw: list[str]) -> str:
    if "sphynx" in raw:
        return "Сфинкс"
    if any(c.startswith("lion") for c in raw):
        return "Лев"
    if "griffin" in raw:
        return "Грифон"
    return "неизвестно"


