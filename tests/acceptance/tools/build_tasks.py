def A(ru, ka, house=None, corner=None, raw=None, kind="street", alt=()):
    return {"street_ru": ru, "street_ka": ka, "alt_ka": list(alt), "kind": kind, "house": house,
            "corner_with": corner, "raw_address": raw}


def F(q, mx=30):
    """Query that uses only facts from the riddle (no answer name)."""
    return {"q": q, "mode": "facts", "expects": "answer street in results", "max_results_ok": mx}


def N(q, mx=10):
    """Query with the name the player deduced by solving the riddle."""
    return {"q": q, "mode": "name", "expects": "answer street in results", "max_results_ok": mx}


