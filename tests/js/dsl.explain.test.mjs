test('labels from the evaluator replace raw values', () => {
  const { ast } = parse('в:сололак');
  const labels = new Map([[ast.expr.items[0], 'Сололаки']]);
  assert.equal(explain(ast, { labels }), 'Объекты в Сололаки');
});
