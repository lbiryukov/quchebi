// explain(): connected Russian sentences for parsed queries.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { parse } from '../../app/src/dsl/parser.js';
import { explain } from '../../app/src/dsl/explain.js';

const ex = (q, opts) => {
  const r = parse(q);
  assert.ok(!r.error, `${q}: ${r.error && r.error.message}`);
  return explain(r.ast, opts);
};

test('golden examples read as sentences', () => {
  const cases = [
    ['дом:3', 'Объекты с домом 3'],
    ['тип:улица* дом:3', 'Улицы, проспекты и т.п. с домом 3'],
    ['тип:переулок x:(тип:улица* кто:поэт)', 'Переулки, пересекающие улицы, проспекты и т.п. (кто: поэт)'],
    ['кто:хормейстер дом:24', 'Объекты (кто: хормейстер) с домом 24'],
    ['кто:наука дом:2', 'Объекты (кто: наука) с домом 2'],
    ['кто:дирижёр было:крылов', 'Объекты (кто: дирижёр) с прежним названием «крылов»'],
    ['было:(био:гэс)', 'Объекты с прежним названием (био: «гэс»)'],
    ['имя:/\\С{5}/', 'Объекты с названием по шаблону /\\С{5}/'],
    ['x:(тип:сквер рижск)~в дом:16', 'Объекты, уходящие на восток от перекрёстка со скверами с «рижск» в названии, с домом 16'],
    ['x:(чаргали)', 'Объекты, пересекающие «чаргали»'],
    ['тип:тупик дом:нет в:сололаки', 'Тупики без номеров домов, в Сололаки'],
    ['кто:писатель пол:ж', 'Объекты (кто: писатель, пол: женский)'],
    ['тип:улица -кто:персона', 'Улицы (кто: не персона)'],
    ['рядом:(тип:метро)~300 тип:переулок*', 'Переулки, тупики и проезды в радиусе 300 м от станций метро'],
    ['семья:важа-пшавела', 'Объекты из семьи «важа-пшавела»'],
  ];
  for (const [q, want] of cases) assert.equal(ex(q), want, q);
});

test('zone suffixes', () => {
  const q = 'тип:переулок x:(тип:улица* кто:поэт)';
  assert.equal(ex(q, { zone: 'default' }), 'Переулки, пересекающие улицы, проспекты и т.п. (кто: поэт) — в зоне');
  assert.equal(ex(q, { zone: 'touch' }).endsWith(' — задевают зону'), true);
  assert.equal(ex(q, { zone: 'whole' }).endsWith(' — целиком в зоне'), true);
  assert.equal(ex(q, { zone: 'off' }).endsWith(' — весь город (зона выключена)'), true);
  assert.equal(ex(q, { zone: null }).endsWith(' — весь город'), true);
  assert.equal(ex(q).includes('—'), false, 'no zone suffix without opts.zone');
});

