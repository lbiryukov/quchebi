"""Stage ``batches``: JSONL batch files for the Haiku subagents.

* classifier: queue dossiers ``cNNN.jsonl``, gold (calibration) ``kNNN.jsonl``, former names
  ``oNNN.jsonl`` -- 40 dossiers per file;
* verifier: blind dossiers ``vNNN.jsonl`` (10% sample of decided families + every LLM/rules conflict);
* disambiguator: ONE family per file ``dNNN.jsonl`` with an extended dossier (classifier answer,
  longer Wikipedia intros);
* name_qa: ``qNNN.jsonl`` -- ka/ru/en mismatches and unmatched ``addr:street``.

Dossiers whose answer is already cached in ``llm_result`` (same prompt version, model and
dossier) are skipped. Before rewriting, existing result files are ingested into ``llm_result``
and moved to ``results/<role>/archive/<timestamp>/`` together with the old batch files.
"""
from __future__ import annotations

import collections
import shutil
import sqlite3
import time
from pathlib import Path

from pipeline.enrich.common import (agent_prompt_version, paths, canonical, llm_cache_key,
                                    read_jsonl, sha1, stage_path, read_json, write_json, write_jsonl)
from pipeline.log import get_logger, stage
from pipeline.wikidata.client import WikidataClient

log = get_logger(__name__)

BATCH_SIZE = 40
EXT_CHARS = 1500


def blind(dossier: dict) -> dict:
    """Verifier input: the dossier without anything that hints at an answer or at the queue."""
    d = {k: v for k, v in dossier.items() if k not in ("queue_reasons",)}
    if d.get("candidates"):
        d["candidates"] = [{k: v for k, v in c.items() if k != "found_by"} for c in d["candidates"]]
    return d


def cached_keys(con: sqlite3.Connection, role: str) -> set[str]:
    return {k for (k,) in con.execute("SELECT cache_key FROM llm_result WHERE role=?", (role,))}


def archive(role: str, base_batches: Path | None = None, base_results: Path | None = None) -> int:
    """Move old batch and result files aside; batches without any result file are simply replaced."""
    base_batches = base_batches or paths.batches
    base_results = base_results or paths.results
    if not any((base_results / role).glob("*.json")) if (base_results / role).exists() else True:
        old = sorted((base_batches / role).glob("*.jsonl")) if (base_batches / role).exists() else []
        for f in old:
            f.unlink()          # generated by an earlier `batches` run and never answered
        return 0
    ts = time.strftime("%Y%m%d-%H%M%S")
    n = 0
    for base, pat in ((base_batches / role, "*.jsonl"), (base_results / role, "*.json")):
        files = sorted(base.glob(pat)) if base.exists() else []
        if not files:
            continue
        dst = base / "archive" / ts
        dst.mkdir(parents=True, exist_ok=True)
        for f in files:
            shutil.move(str(f), str(dst / f.name))
            n += 1
    return n


def _chunks(rows: list[dict], size: int) -> list[list[dict]]:
    return [rows[i:i + size] for i in range(0, len(rows), size)]


def extended(dossier: dict, answer: dict, client: WikidataClient | None) -> dict:
    d = dict(dossier)
    d["classifier_answer"] = answer
    if client is not None and d.get("candidates"):
        cands = []
        for c in d["candidates"]:
            c = dict(c)
            for wiki, lang in (("kawiki", "ka"), ("ruwiki", "ru")):
                t = c.get(f"{wiki}_title")
                if t:
                    txt = client.extracts(lang, [t], chars=EXT_CHARS).get(t, "")
                    if txt:
                        c[f"{wiki}_intro"] = txt[:EXT_CHARS]
            cands.append(c)
        d["candidates"] = cands
    return d


def plan(con: sqlite3.Connection, dossier_rows: list[dict], merge_state: dict | None,
         client: WikidataClient | None) -> dict[str, dict[str, list[dict]]]:
    """role -> prefix -> list of batch lines (dossiers, already filtered by the cache)."""
    out: dict[str, dict[str, list[dict]]] = {r: collections.defaultdict(list) for r in
                                             ("classifier", "verifier", "disambiguator", "name_qa")}
    pv = {r: agent_prompt_version(r) for r in out}
    have = {r: cached_keys(con, r) for r in out}
    by_fid: dict[str, dict] = {}
    for row in dossier_rows:
        meta, d = row["meta"], row["dossier"]
        kind = meta["kind"]
        if kind in ("queue", "gold", "old_name"):
            if kind != "gold":
                by_fid[d["family_id"]] = row
            if llm_cache_key(*pv["classifier"], d) not in have["classifier"]:
                out["classifier"][{"queue": "c", "gold": "k", "old_name": "o"}[kind]].append(d)
        elif kind == "verify":
            b = blind(d)
            if llm_cache_key(*pv["verifier"], b) not in have["verifier"]:
                out["verifier"]["v"].append(b)
        elif kind == "name_qa":
            if llm_cache_key(*pv["name_qa"], d) not in have["name_qa"]:
                out["name_qa"]["q"].append(d)
    ms = (merge_state or {}).get("families", {})
    for fam_id, st in sorted(ms.items()):
        row = by_fid.get(fam_id)
        if row is None:
            continue
        if st.get("needs_verifier"):
            b = blind(row["dossier"])
            if llm_cache_key(*pv["verifier"], b) not in have["verifier"]:
                out["verifier"]["v"].append(b)
        if st.get("route") == "second_opinion" and st.get("answer") is not None:
            ext = extended(row["dossier"], st["answer"], client)
            if llm_cache_key(*pv["disambiguator"], ext) not in have["disambiguator"]:
                out["disambiguator"]["d"].append(ext)
    # de-duplicate (a family can be both in the random sample and a conflict)
    for role in out:
        for p in out[role]:
            seen, uniq = set(), []
            for d in out[role][p]:
                h = sha1(canonical(d))
                if h not in seen:
                    seen.add(h)
                    uniq.append(d)
            out[role][p] = sorted(uniq, key=lambda d: d.get("family_id") or d.get("item_id"))
    return out


def run(con: sqlite3.Connection, dossier_rows: list[dict], client: WikidataClient | None,
        roles: tuple[str, ...] = ("classifier", "verifier", "disambiguator", "name_qa"), size: int = BATCH_SIZE,
        batch_dir: Path | None = None, result_dir: Path | None = None, merge_state: dict | None = None) -> dict:
    batch_dir = batch_dir or paths.batches
    result_dir = result_dir or paths.results
    from pipeline.enrich.merge import dossier_keys, ingest  # avoid an import cycle
    with stage(log, "enrich.batches", dossiers=len(dossier_rows)) as st:
        keys = dossier_keys(dossier_rows)
        for role in roles:
            st[f"ingested_{role}"] = ingest(con, role, batch_dir, result_dir, keys)
        if merge_state is None:
            merge_state = read_json(stage_path("merge"), {}) or {}
        p = plan(con, dossier_rows, merge_state, client)
        manifest_all = {}
        for role in roles:
            st[f"archived_{role}"] = archive(role, batch_dir, result_dir)
            pv, model = agent_prompt_version(role)
            manifest = {"role": role, "prompt_version": pv, "model": model,
                        "created": time.strftime("%d/%m/%Y %H:%M"), "batches": {}}
            for prefix, rows in sorted(p[role].items()):
                per = 1 if role == "disambiguator" else size
                for i, chunk in enumerate(_chunks(rows, per), 1):
                    name = f"{prefix}{i:03d}"
                    write_jsonl(batch_dir / role / f"{name}.jsonl", chunk)
                    manifest["batches"][name] = {"n": len(chunk),
                                                 "ids": [d.get("family_id") or d.get("item_id") for d in chunk],
                                                 "result": str((result_dir / role / f"{name}.json").as_posix())}
            write_json(batch_dir / role / "manifest.json", manifest)
            (result_dir / role).mkdir(parents=True, exist_ok=True)
            manifest_all[role] = manifest
            st[f"{role}_batches"] = len(manifest["batches"])
            st[f"{role}_items"] = sum(b["n"] for b in manifest["batches"].values())
    return manifest_all


def load_dossiers(paths: list[Path]) -> list[dict]:
    rows: list[dict] = []
    for p in paths:
        rows += read_jsonl(p)
    return rows
